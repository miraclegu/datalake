# -*- coding: utf-8 -*-
"""换手率（13）—— 1 条 ✅✅ 实测定案 + 12 条 ✅。

公式出处：`因子实现规格.md` 的「换手率」一节。

🔴 **`turnover` 是百分数**：0.0883 表示 0.0883%，不是 8.83%。
  当成小数用会让所有换手类因子小 100 倍，**而它不报错** ——
  只是那一批因子的分位切点整体挪位（同「dy / inc_* 在 std 层是小数」那条）。
  所以这一族的单位一律标「百分数」，让量纲写在脸上。
"""
from . import Spec, register

_AVG = [(5, '5日平均换手率'), (10, '10日平均换手率'), (20, '20日平均换手率'),
        (60, '60日平均换手率'), (120, '120日平均换手率'), (240, '240日平均换手率')]
_RATIO = [(5, 'to_ratio5', '5日平均换手率与120日平均换手率'),
          (10, 'to_ratio10', '10日平均换手率与120日平均换手率之比'),
          (20, 'to_ratio20', '20日平均换手率与120日平均换手率之比')]

register(
    [Spec('to_ma%d' % n, cn, 'turn',
          'MA(TO, %d)' % n,
          '最近 %d 天的平均换手率。换手率高 = 筹码换手快、关注度高。'
          '🔴 单位是【百分数】：0.0883 就是 0.0883%%，别当成小数' % n,
          '百分数', ('turnover',), n,
          (lambda n: lambda x: x.ma('turnover', n))(n))
     for n, cn in _AVG] +

    [Spec(fid, cn, 'turn',
          'MA(TO, %d) / MA(TO, 120)' % n,
          '短期换手相对长期的倍数：>1 说明最近成交在放大。'
          '★ 比值消掉了量纲，所以它【跨股票可比】，而 to_ma%d 不可比' % n,
          '倍', ('turnover',), 120,
          (lambda n: lambda x: x.ma('turnover', n) / x.ma('turnover', 120))(n))
     for n, fid, cn in _RATIO] +

    [
        Spec('to_std20', '换手率相对波动率', 'turn',
             'STD_样本(TO, 20) ÷ 100',
             '换手率自身的波动，衡量成交的稳定程度。'
             '🔴 那个 ÷100 是【定案的一部分】不是笔误 —— 逐只实测过：'
             '300179 = 0.504361/100 = 0.005044，与聚宽精确一致。'
             '也不要自己用 V / 流通股本 去算换手率再求标准差',
             '小数', ('turnover',), 21,
             lambda x: x.std_samp('turnover', 20) / 100.0,
             tier='exact'),

        Spec('to_sum20', '月换手率', 'turn',
             'Σ₂₀ TO',
             '20 个交易日（约一个月）的换手率累计，近似"这一个月换了几成手"',
             '百分数', ('turnover',), 20,
             lambda x: x.rsum('turnover', 20)),

        Spec('to_m_q', '季度平均平均月换手率', 'turn',
             'Σ₆₀ TO / 3',
             '一个季度（60 个交易日）里的月均换手。'
             '⚠ 原名「季度平均平均月换手率」有个重复的"平均"，'
             '这里照抄原名不改 —— 改了就对不回 factors.xlsx 那一行',
             '百分数', ('turnover',), 60,
             lambda x: x.rsum('turnover', 60) / 3.0),

        Spec('to_m_y', '年度平均月换手率', 'turn',
             'Σ₂₄₀ TO / 12',
             '一年（240 个交易日）里的月均换手，最钝的那档',
             '百分数', ('turnover',), 240,
             lambda x: x.rsum('turnover', 240) / 12.0),
    ]
)
