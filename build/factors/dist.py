"""收益分布 / 波动（10）—— 全部 ✅。

公式出处：`因子实现规格.md` 的「收益分布 / 波动」一节。

⚠ 这一组原有 14 条，这里【只做 10 条】，剔掉的 4 条各有原因：
  - 20/60/120 日【夏普比率】 ×3：要无风险利率 r_f，而【本地没有 r_f 序列】。
    取 0 还是 0.04 是一个待定口径 —— 编一个数就是造数（同「拿不到分红
    那一格标『查不到』，不猜一个数填上去」）。
  - 「1 减去 过去一个月收益率排名与股票总数的比值」：它是【横截面】的
    （要当日全市场的排名与只数），而股票池口径（剔不剔 ST/次新/停牌）
    同样待定。【形状也不同】 —— 横截面因子得在全市场对齐之后算，
    不能在"逐只票滚动"这一层做。

所以这 4 条【不是漏了】，是前置口径没定。定了再补。
"""
from . import Spec, register


_N3 = [20, 60, 120]

register(
    [Spec('skew%d' % n, '个股收益的%d日偏度' % n, 'dist',
          'SKEW(R, %d)　R = 后复权日收益' % n,
          '收益分布的不对称程度。正偏 = 偶有大涨、多数小跌；'
          '负偏反之。小市值票常见正偏',
          '无量纲', ('close_hfq',), n + 1,
          (lambda n: lambda x: x.skew('_ret', n))(n))
     for n in _N3] +

    [Spec('kurt%d' % n, '个股收益的%d日峰度' % n, 'dist',
          'KURT(R, %d)（pandas 口径：超额峰度，正态 = 0）' % n,
          '收益分布的尾部厚度。越大说明极端涨跌越频繁。'
          '🔴 pandas 的 `kurt` 给的是【超额】峰度（正态是 0 不是 3）—— '
          '与别处的峰度比大小之前先确认对方是哪个口径',
          '无量纲', ('close_hfq',), n + 1,
          (lambda n: lambda x: x.kurt('_ret', n))(n))
     for n in _N3] +

    [Spec('var%d' % n, '%d日收益方差' % n, 'dist',
          'VAR_样本(R, %d)（除 N−1）' % n,
          '日收益的方差，风险的最直接度量。'
          '🔴 这里是【样本】方差（除 N−1）；而 BOLL 那边的 σ 是【总体】的 —— '
          '两处口径不同是有意的：那边是通道宽度、这里是统计量',
          '小数²', ('close_hfq',), n + 1,
          (lambda n: lambda x: x.var_samp('_ret', n))(n))
     for n in _N3] +

    [
        Spec('std20', '日收益率标准差', 'dist',
             'STD_样本(R, 20)',
             '20 日日收益标准差 = 最常用的波动率代理。'
             '⚠ Barra 的 DASTD 用 252 日【半衰加权】，那是另一个口径 —— '
             '两者不可互换（同「别人的『股息率』里藏着别人的窗口」）',
             '小数', ('close_hfq',), 21,
             lambda x: x.std_samp('_ret', 20)),
    ]
)
