def main():
    print('=' * 86)
    print(' 流通股本护栏对数   样本 %d 条（本地分层抽样，护栏抬高 >5%%）' % len(SAMPLE))
    print('=' * 86)
    print(' %-13s %-12s %10s %10s %10s   谁更贴聚宽' %
          ('代码', '日期', '聚宽万股', '护栏开', '护栏关'))
    win_on = win_off = tie = bad = 0
    rows = []
    for code, d, on_w, off_w in SAMPLE:
        try:
            q = query(valuation.code, valuation.circulating_market_cap,
                      valuation.circulating_cap).filter(valuation.code == code)
            df = get_fundamentals(q, date=d)
        except Exception as e:
            print(' %-13s %-12s  取数失败：%s' % (code, d, str(e)[:40]))
            bad += 1
            continue
        if len(df) == 0:
            print(' %-13s %-12s  聚宽没有这一天的估值（停牌/未上市/已退市）' % (code, d))
            bad += 1
            continue
        # circulating_cap 单位是【万股】，正是我们要比的量
        jq_w = float(df['circulating_cap'].iloc[0])
        d_on = abs(on_w - jq_w) / jq_w * 100.0
        d_off = abs(off_w - jq_w) / jq_w * 100.0
        if abs(d_on - d_off) < 0.5:
            who, tie = '一样', tie + 1
        elif d_on < d_off:
            who, win_on = '护栏开 ✅', win_on + 1
        else:
            who, win_off = '护栏关 ✅', win_off + 1
        rows.append((code, d, jq_w, on_w, off_w, d_on, d_off, who))
        print(' %-13s %-12s %10.0f %10.0f %10.0f   %-9s (差 %.1f%% / %.1f%%)'
              % (code, d, jq_w, on_w, off_w, who, d_on, d_off))

    print()
    print('=' * 86)
    n = win_on + win_off + tie
    print(' 总计 %d 条可比：护栏开胜 %d · 护栏关胜 %d · 一样 %d · 取不到 %d'
          % (n, win_on, win_off, tie, bad))
    if n:
        print('        护栏开 %.1f%% / 护栏关 %.1f%%'
              % (100.0 * win_on / n, 100.0 * win_off / n))
    print()
    print(' ---- 三个已知案例单独看（它们决定判据该怎么写）----')
    for code, d, jq_w, on_w, off_w, d_on, d_off, who in rows:
        if code in ('603536.XSHG', '001256.XSHE', '301062.XSHE'):
            print('   %-13s %-12s 聚宽 %8.0f  开 %8.0f  关 %8.0f  -> %s'
                  % (code, d, jq_w, on_w, off_w, who))
    print('=' * 86)


main()
