# ============================================================================
# 流通股本「定期报告护栏」对数探针（聚宽研究环境）
#
# ## 要判的事
#
#   `build_panel_daily.py` 重建流通股本时有一道护栏：
#     「定期报告【不得】把流通股压到低于最近一个【事件行】的值」
#   它是为 603536.XSHG 那个源数据回退建的（2018-06-30 定期报告说 4200 万，
#   而 2018-06-13 限售股份上市说 6025 万，2018-12-31 又回到 6025）。
#
#   2026-09-28 实测发现它会**误伤真实下降**：
#     001256.XSHE  2025-12-12 限售股份上市 流通 14132 / 限售  129
#                  2025-12-31 定期报告     流通 10691 / 限售 3570  <- 股份重新锁定
#     301062.XSHE  2026-03-31 可转债转股   流通 31324 / 限售 12005
#                  2026-06-30 定期报告     流通 27525 / 限售 15804  <- 转股后结构调整
#   两例的「总股本 = 流通 + 限售」都成立，恒等式区分不了；幅度也不是双峰。
#   唯一能分开的是「后续是否弹回」，而那要等下一期定期报告才知道 —— 前视，
#   不能当 PIT 判据。
#
# ## 为什么必须来聚宽问
#
#   本地还有一个来源 `floatmv_tdx`（tdx 日频流通市值），但它**不独立**：
#   tdx 的模型就是「只看 change_date、没有护栏」，所以「关掉护栏更像 tdx」
#   是同义反复。而且实测 603536 那半年 tdx 给的正是 4200 —— 与护栏立案时
#   「聚宽同期根本没买它」矛盾。**tdx 不能当真值。**
#
#   聚宽的 `valuation.circulating_market_cap` 是独立的第三方口径，
#   而这个策略本来就是聚宽移植 —— 对得上它才叫对。
#
# ## 判据
#
#   对每个 (代码, 日期)，比 `护栏开` / `护栏关` 两个流通股数哪个更贴聚宽。
#   逐条给结论，末尾给总计。**样本是本地分层抽的**（每年最多 4 条，
#   全部是护栏抬高 >5% 的，外加 603536 / 001256 / 301062 三个已知案例）。
#
# 用法：聚宽 -> 研究环境 -> 新建 notebook -> 粘贴全文 -> 运行。不用改任何东西。
# ============================================================================
